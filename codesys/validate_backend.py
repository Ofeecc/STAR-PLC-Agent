"""Real CODESYS valid-invalid-repaired backend check; no LLM or mock compiler.

Run with Project1 and PYTHONPATH=<project>/src. Never count this fixture as a
benchmark task or claim the manually repaired body was generated by a model.
"""
import json
import sys
from dataclasses import asdict
from datetime import datetime

from plc_agent.common import ROOT, write_json
from plc_agent.compiler import compile_st
from plc_agent.config import Settings


def main():
    cfg = Settings.load()
    stamp = datetime.now().strftime("%Y%m%d_%H%M%S_%f")
    folder = ROOT / "results/raw/compiler_smoke" / stamp
    folder.mkdir(parents=True)
    summary = {"kind": "REAL_CODESYS_BACKEND_VALIDATION", "status": "NOT_RUN",
               "automatic_model_repair": False, "runs": [],
               "expected": ["PASS", "COMPILE_FAIL", "PASS"]}
    missing = cfg.compiler_ready()
    if missing:
        summary["reason"] = "Missing compiler configuration: " + ", ".join(missing)
    else:
        declaration = "FUNCTION_BLOCK FB_Task\nVAR_INPUT\n x : BOOL;\nEND_VAR\nVAR_OUTPUT\n y : BOOL;\nEND_VAR"
        fixtures = [("valid", "y := x;"), ("invalid", "y := ;"), ("repaired", "y := x;")]
        for name, body in fixtures:
            candidate = {"declaration": declaration, "implementation": body, "supporting_objects": []}
            result = compile_st({"id": "COMPILER_SMOKE_" + name.upper()}, candidate, folder / name, cfg)
            summary["runs"].append({"fixture": name, **asdict(result)})
            if result.infrastructure_error:
                summary["reason"] = "Infrastructure failure; remaining fixtures not executed"
                break
        actual = [run["status"] for run in summary["runs"]]
        summary["status"] = "PASS" if actual == summary["expected"] else "FAIL"
    write_json(folder / "summary.json", summary)
    print(json.dumps({"status": summary["status"], "summary": str(folder / "summary.json"),
                      "actual": [run["status"] for run in summary["runs"]]}, indent=2))
    return 0 if summary["status"] == "PASS" else 2


if __name__ == "__main__":
    sys.exit(main())
