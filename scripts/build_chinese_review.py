def main():
    tasks = load_tasks()
    before = digest(tasks)
    pilot = {r['id']:r for r in read_json(ROOT/'configs/pilot_review.json')['tasks']}
    rows=[]
    for task in tasks:
        tid=task['id']
        if tid in pilot:
            row=deepcopy(pilot[tid])
        else:
            title,translation,assumptions,notes,descriptions=CONTENT[tid]
            properties=[p for p in task['ltl'] if p['formula'] not in ('G(CompleteBehavior)', 'G(CompleteBehaviorV2)')]
            assert len(properties)==len(descriptions), (tid,len(properties),len(descriptions))
            props={p['id']:{'formula':p['formula'],'description':d,'review':notes} for p,d in zip(properties,descriptions)}
            for p in task['ltl']:
                if p['formula'] in ('G(CompleteBehavior)', 'G(CompleteBehaviorV2)'):
                    props[p['id']]={'formula':p['formula'],'description':'每次调用的全部输出与保留历史必须满足完整行为关系；具体转移规则见上方完整规约。','review':'CompleteBehavior是解释性复合谓词；必须显式展开并绑定实际候选输出后才能模型检查，不能把名称当成已完成证明。'}
            row={'id':tid,'title_zh':title,'translation_zh':translation,'assumptions_zh':assumptions,'review_points_zh':notes,'properties_zh':props}
        # Rebind editorial translations to the versioned normalized definitions.
        for prop in task['ltl']:
            item=row['properties_zh'][prop['id']]
            changed=item['formula']!=prop['formula']
            item['formula']=prop['formula']
            if prop['formula'] in ('G(CompleteBehavior)', 'G(CompleteBehaviorV2)'):
                item['description']='每拍将独立参考转移的期望结果与候选实际输出逐项比较；转移、初值、数值比较和不约束字段均有固定定义。'
                item['review']='这是已定义并完成人工审阅的扫描谓词；不代表已完成 ST 模型转换或无限时序证明。'
            elif tid=='PUB002' and prop['id'] in ('P6', 'PUB002.P6'):
                item['description']='对DWORD的0～31位逐位比较：本拍输入位等价于下一拍输入历史位。X只作用于布尔位命题，前值初始全0。'
            elif tid=='PUB009' and prop['id'] in ('P6', 'PUB009.P6'):
                item['description']='本拍布尔trigger等价于下一拍布尔previousTrigger；非法窗、复位等分支也必须更新输入历史。'
            if changed:
                item['review']+=' 本轮公式已规范化，请重新核对含义；量化按绑定长度有限展开。'
        pin_text=INTERFACES[tid].split('|')
        test_text=TESTS[tid].split('|')
        assert len(pin_text)==len(task['interface']),tid
        assert len(test_text)==len(task['tests']),tid
        row['interface_zh']={p['name']:s for p,s in zip(task['interface'],pin_text)}
        row['tests_zh']={c['id']:{'name':s,'purpose':s,'source_sha256':digest(c)} for c,s in zip(task['tests'],test_text)}
        row['coverage_zh']='\n'.join(f"{c['id']}：{s}（{len(c['steps'])}步）。" for c,s in zip(task['tests'],test_text))
        row['source_task_sha256']=digest(task)
        row['review_status']='HUMAN_REVIEWED'
        row['material_origin']='GROUP_TRANSLATION_AND_REVIEW_NOT_TEACHER_SPEC'
        row['source_kind']=task['kind']
        row['title_en']=task['title']
        complete=(task.get('specification_contract') or {}).get('normative_completion','')
        row['complete_behavior_zh']=complete if any('\u4e00'<=ch<='\u9fff' for ch in complete) else ('每拍全部输出应与独立状态转移规则一致，按初值建立并逐拍更新历史。完整转移要求：'+row['translation_zh'])
        rows.append(row)
    output={'version':'2026-11-14','description':'Display-only Chinese translations; human specification review completed (dataset freeze, not formal proof or candidate ST verification).', 'dataset_sha256':before,'tasks':rows}
    write_json(ROOT/'configs/task_review_zh.json',output)
    # Keep the original six-task entry point current as well.
    write_json(ROOT/'configs/pilot_review.json',{'description':'六题规范化审核材料；已完成人工审阅，不构成形式证明或候选 ST 验证。',
        'tasks':[r for tid in pilot for r in rows if r['id']==tid]})
    assert digest(load_tasks())==before,'Benchmark inputs unexpectedly changed'
    print(f"Built {len(rows)} task reviews, {sum(len(r['properties_zh']) for r in rows)} property descriptions, all interfaces and fixed-test labels; dataset unchanged.")

if __name__=='__main__':main()
